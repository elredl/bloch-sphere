#!/usr/bin/env python3
"""Writes docs/PARTICIPANT_TEXT.md: every piece of text a participant can see in the app,
taken from the data files the app reads, for review and for the IRB application.
Run from the project root after changing any wording:  python3 tools/export_participant_text.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "Assets/Study/Data"
OUT = ROOT / "docs/PARTICIPANT_TEXT.md"

session = json.loads((DATA / "session_text.json").read_text(encoding="utf-8"))
feedback = json.loads((DATA / "pause_feedback.json").read_text(encoding="utf-8"))
timeline = json.loads((DATA / "lesson_timeline.json").read_text(encoding="utf-8"))

# (screen, when it is shown, headset key, desktop key). A missing key: not shown there.
SESSION_ROWS = [
    ("Calibration", "headset only, before orientation", "calibrationTitle", "calibrationTitle"),
    ("", "", "calibrationVr", None),
    ("Ready", "before orientation", "readyTitle", "readyTitle"),
    ("", "", "readyVr", "readyDesktop"),
    ("Practice", "orientation (2:00), all conditions", "practiceTitle", "practiceTitle"),
    ("", "step 1: select", "selectVr", "selectDesktop"),
    ("", "step 2: press", "pressVr", "pressDesktop"),
    ("", "button label", "pressLabel", "pressLabel"),
    ("", "step 3: rotate", "rotateVr", "rotateDesktop"),
    ("", "after a round", "roundDone", "roundDone"),
    ("Break", "break (headset off, or B on the desktop)", "breakTitle", "breakTitle"),
    ("", "while paused", "breakKey", "breakKey"),
    ("", "headset back on", "breakResumeVr", None),
    ("", "headset back on, small print", "breakResumeHint", None),
    ("Stopping", "while the experimenter holds the stop buttons", "abortHold", "abortHold"),
    ("End", "after the lesson or a stop", "endTitle", "endTitle"),
    ("", "lesson completed", "endCompletedVr", "endCompletedDesktop"),
    ("", "session stopped", "endStoppedVr", "endStoppedDesktop"),
    ("", "button (for the experimenter)", "experimenterButton", "experimenterButton"),
]


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def get(key):
    return session.get(key) if key else None


lines = [
    "# Participant-facing text",
    "",
    "Generated by `tools/export_participant_text.py` from `Assets/Study/Data/` (do not edit by hand).",
    "This is every piece of text a participant can see in the app. The lesson narration (audio)",
    "is scripted in `docs/NARRATION_SCRIPT.md` (draft).",
    "",
    "## Session screens (all conditions)",
    "",
    "The headset and desktop versions differ only where the input or device differs.",
    "",
    "| Screen | Shown | Headset (Conditions 2 and 3) | Desktop (Condition 1) |",
    "|---|---|---|---|",
]
for screen, when, vr, desktop in SESSION_ROWS:
    v, d = get(vr), get(desktop)
    d_text = "(not shown)" if desktop is None else ("same" if d == v else cell(d))
    lines.append(f"| {screen} | {when} | {cell(v)} | {d_text} |")

lines += [
    "",
    "## Lesson display (all conditions)",
    "",
    "- Sphere labels: |0⟩, |1⟩, x, y; angle labels θ and φ when the angles are shown.",
    "- Measurement panel (pause 4 and the scripted measurement demos): title MEASUREMENTS, a",
    "  shot counter such as 37 / 100, bar labels |0⟩ and |1⟩ with their counts.",
    "",
    "## Pause prompts and feedback (Condition 3 only)",
    "",
    "Panel titles and hints:",
    "",
    "| Key | Text |",
    "|---|---|",
]
for key, text in feedback["ui"].items():
    lines.append(f"| {key} | {cell(text)} |")

tasks = {t["id"]: t for t in timeline["pauseTasks"]}
for t in feedback["tasks"]:
    task = tasks.get(t["id"], {})
    lines += ["", f"### {t['id']}", ""]
    if task:
        choices = task.get("choices", [])
        shown = [c + "%" for c in choices] if task.get("prediction") == "p0" else ["|" + c.replace("-", "−") + "⟩" for c in choices]
        lines.append(f"- Answers: {', '.join(shown)}")
        lines.append(f"- Button: {task.get('operationLabel', '')}")
    lines += [
        f"- Prompt: {t['prompt']}",
        f"- Correct: {t['correct']}",
        f"- No prediction made: {t['noPrediction']}",
        f"- Other wrong answers: {t['genericIncorrect']}",
    ]
    for m in t["misconceptions"]:
        answers = ", ".join(m["answers"])
        lines.append(f"- Wrong answer {answers} ({m['id']}): {m['text']}")

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}")
